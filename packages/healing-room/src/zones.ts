export function zoneFootprint(
  layoutId: HealingLayoutId,
  zoneId: HealingZoneId,
): ZoneFootprint {
  const layout = healingLayoutById(layoutId)
  const footprint = layout.footprints.find((item) => item.id === zoneId)
  if (!footprint) throw new Error(`Layout ${layoutId} has no footprint for ${zoneId}`)
  return footprint
}

/** True when the inner footprint is fully contained in the outer one. */
export function footprintContains(
  outer: ZoneFootprint,
  inner: ZoneFootprint,
): boolean {
  const halfOuterW = outer.widthM / 2
  const halfOuterD = outer.depthM / 2
  const halfInnerW = inner.widthM / 2
  const halfInnerD = inner.depthM / 2
  return (
    inner.xM - halfInnerW >= outer.xM - halfOuterW &&
    inner.xM + halfInnerW <= outer.xM + halfOuterW &&
    inner.zM - halfInnerD >= outer.zM - halfOuterD &&
    inner.zM + halfInnerD <= outer.zM + halfOuterD
  )
}
