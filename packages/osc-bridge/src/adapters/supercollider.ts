import type { SpatialAudioSession } from '@aura-spec/core-acoustics'
import { AURA_OSC_NAMESPACE, rendererAddress, sourceAddress, speakerAddress } from '../address-space'

export interface SuperColliderOptions {
  port?: number
  namespace?: string
  bindAddress?: string
}

/**
 * Generates a deterministic SuperCollider receiver for a session. It is a
 * starting point for a spatialisation synth; replace the dictionary writes with
 * your own `Synth`/`Ndef` parameter updates.
 */
export function generateSuperColliderReceiver(
  session: SpatialAudioSession,
  options: SuperColliderOptions = {},
): string {
  const port = options.port ?? 9000
  const namespace = options.namespace ?? AURA_OSC_NAMESPACE
  const bindAddress = options.bindAddress ?? '0.0.0.0'
  const lines: string[] = [
    '// AURA-SPEC OSC receiver — generated by @aura-spec/osc-bridge',
    `// Session: ${session.id}`,
    '(',
    `~auraPort = ${port};`,
    `~auraBind = "${scEscape(bindAddress)}";`,
    '~auraSources = IdentityDictionary.new;',
    '~auraRenderer = IdentityDictionary.new;',
    '~auraTransport = IdentityDictionary.new;',
    '~auraSpeakers = IdentityDictionary.new;',
    '',
    '// Source state',
  ]

  for (const source of session.sources) {
    const id = scSymbol(source.id)
    const prefix = `~auraSources.at(\\${id})`
    lines.push(
      `if(${prefix}.isNil) { ~auraSources.put(\\${id}, IdentityDictionary.new); };`,
      `OSCdef(\\aura_${id}_position, { |msg| ${prefix}.put(\\position, msg[1..3]); }, "${scEscape(sourceAddress(session.id, source.id, 'position', namespace))}");`,
      `OSCdef(\\aura_${id}_orientation, { |msg| ${prefix}.put(\\orientation, msg[1..3]); }, "${scEscape(sourceAddress(session.id, source.id, 'orientation', namespace))}");`,
      `OSCdef(\\aura_${id}_gain, { |msg| ${prefix}.put(\\gain, msg[1]); }, "${scEscape(sourceAddress(session.id, source.id, 'gain', namespace))}");`,
      `OSCdef(\\aura_${id}_spread, { |msg| ${prefix}.put(\\spread, msg[1]); }, "${scEscape(sourceAddress(session.id, source.id, 'spread', namespace))}");`,
      '',
    )
  }

  lines.push('// Renderer state')
  for (const leaf of ['order', 'mode', 'sample-rate', 'block-size', 'layout'] as const) {
    lines.push(
      `OSCdef(\\aura_renderer_${leaf.replace('-', '_')}, { |msg| ~auraRenderer.put(\\${leaf.replace('-', '_')}, msg[1]); }, "${scEscape(rendererAddress(session.id, leaf, namespace))}");`,
    )
  }

  lines.push('', '// Transport state')
  for (const leaf of ['playing', 'bpm', 'position/beats', 'position/seconds'] as const) {
    const key = leaf.replace('/', '_').replace('-', '_')
    lines.push(
      `OSCdef(\\aura_transport_${key}, { |msg| ~auraTransport.put(\\${key}, msg[1]); }, "${scEscape(`${namespace}/transport/${leaf}`)}");`,
    )
  }

  if (session.osc.sendSpeakerDrive) {
    lines.push('', '// Speaker drive trims')
    for (const placement of session.speakerPlacements) {
      const id = scSymbol(placement.id)
      lines.push(
        `if(~auraSpeakers.at(\\${id}).isNil) { ~auraSpeakers.put(\\${id}, IdentityDictionary.new); };`,
        `OSCdef(\\aura_spk_${id}, { |msg| ~auraSpeakers.at(\\${id}).put(\\drive, [msg[1], msg[2], msg[3]]); }, "${scEscape(speakerAddress(session.id, placement.id, 'drive', namespace))}");`,
      )
    }
  }

  lines.push(
    '',
    `OSCdef(\\aura_clock, { |msg| ~auraTransport.put(\\clock, [msg[1], msg[2], msg[3]]); }, "${namespace}/clock");`,
    '',
    '// Example: inspect state',
    '// ~auraSources.postln; ~auraRenderer.postln; ~auraTransport.postln;',
    ')',
    '',
  )

  return lines.join('\n')
}

function scSymbol(value: string): string {
  return value.replace(/[^A-Za-z0-9_]/g, '_')
}

function scEscape(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')
}
