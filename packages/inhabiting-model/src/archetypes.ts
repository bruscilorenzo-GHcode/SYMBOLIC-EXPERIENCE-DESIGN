export const DEFAULT_HABITAT_ID = 'outdoor-mediterranean-garden'

export function habitatArchetypes(domain?: 'indoor' | 'outdoor'): HabitatArchetype[] {
  if (!domain) return HABITAT_ARCHETYPES
  return HABITAT_ARCHETYPES.filter((archetype) => archetype.domain === domain)
}

export function getHabitatArchetype(id: string): HabitatArchetype | undefined {
  return HABITAT_ARCHETYPES.find((archetype) => archetype.id === id)
}

export function requireHabitatArchetype(id: string): HabitatArchetype {
  const archetype = getHabitatArchetype(id)
  if (!archetype) throw new Error(`Unknown habitat archetype "${id}"`)
  return archetype
}
